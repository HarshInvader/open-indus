"""Exp 2. Slot-template grammar with a PROFILE HMM (genomics: profile HMMs /
position-specific scoring matrices for protein families and promoters).

Question: is an Indus text better described as a FIXED FRAME of ordered slots
(each slot = a set of interchangeable signs, slots optional, never revisited)
than as an adjacency chain (bigram)? If yes: what are the slots and fillers?

Models (fit on dev, scored on held-out, bits per sign incl. end-of-text):
  unigram | KN bigram | ergodic HMM (K states) | left-to-right HMM = slot
  template (K slots, forward-only transitions, optional skips, a slot may
  hold a run of signs via a self-loop).
Planted controls: synthetic slot code (6 known slots) and synthetic
logo-syllabic seal legends; null: corpus generated by the Indus bigram.
"""
import sys

from common import *
from hmm import HMM, KNBigram, Vocab, batches, unigram_ll
from sklearn.metrics import adjusted_rand_score

SEEDS = 3


def fit_best(data, K, V, top, selfloop=False):
    best = None
    for s in range(SEEDS):
        m = HMM(K, V, top, selfloop, seed=s)
        ll = m.fit(data)
        if best is None or ll > best[0]:
            best = (ll, m)
    return best[1]


def evaluate(train, test, tag, Ks_lr=(3, 4, 6, 8, 10, 12), Ks_erg=(3, 6, 10, 20), truth=None):
    voc = Vocab(train)
    tr = [voc.enc(t) for t in train]; te = [voc.enc(t) for t in test]
    V = len(voc)
    ntok = sum(len(t) + 1 for t in te)
    dtr, dte = batches(tr), batches(te)
    out = {"n_train": len(train), "n_test": len(test), "V": V}
    out["unigram"] = -unigram_ll(tr, te, V) / ntok / np.log(2)
    out["bigram_kn"] = -KNBigram(tr, V).loglik(te) / ntok / np.log(2)
    models = {}
    for K in Ks_erg:
        m = fit_best(dtr, K, V, "ergodic")
        out["erg%d" % K] = -m.loglik(dte) / ntok / np.log(2); models["erg%d" % K] = m
    for K in Ks_lr:
        m = fit_best(dtr, K, V, "lr", selfloop=True)
        out["lr%d" % K] = -m.loglik(dte) / ntok / np.log(2); models["lr%d" % K] = m
    if truth is not None:
        for name, m in models.items():
            pred, gold = [], []
            for t, x in zip(test, te):
                pred += m.viterbi(x); gold += [truth(s) for s in t]
            out["ARI_" + name] = adjusted_rand_score(gold, pred)
    print(tag, {k: (round(v, 3) if isinstance(v, float) else v) for k, v in out.items()})
    sys.stdout.flush()
    return out, models, voc


def describe(m, voc, train, freq, top=8):
    """Slot table: occupancy, mean relative position, top fillers."""
    K = m.K
    occ = Counter(); pos = defaultdict(list); fill = defaultdict(Counter); paths = Counter()
    for t in train:
        x = voc.enc(t); s = m.viterbi(x)
        paths[tuple(s)] += 1
        for i, (a, b) in enumerate(zip(t, s)):
            occ[b] += 1; fill[b][a] += 1
            pos[b].append(i / (len(t) - 1) if len(t) > 1 else 0.5)
    rows = []
    for k in range(K):
        tot = occ[k] or 1
        rows.append(dict(slot=k, tokens=occ[k], texts_using=round(occ[k] / len(train), 3),
                         mean_relpos=round(float(np.mean(pos[k])) if pos[k] else -1, 2),
                         n_distinct_fillers=len(fill[k]),
                         fillers=[(a, round(n / tot, 2)) for a, n in fill[k].most_common(top)]))
    return rows, paths


def main():
    rng = np.random.default_rng(7)
    D, H = load_split()
    res = {}
    # ---- planted control 1: slot code
    S = slotcode_corpus(len(D) + len(H), rng); idx = rng.permutation(len(S))
    Str = [S[i] for i in idx[:len(D)]]; Ste = [S[i] for i in idx[len(D):]]
    res["slotcode"], _, _ = evaluate(Str, Ste, "slotcode", truth=lambda s: s.split("_")[0])
    # ---- planted control 2: logo-syllabic seal legends
    def ntruth(s):
        return s.split(":")[1].rstrip("0123456789") if s.startswith("L:") else "syll"
    S = names_corpus(len(D) + len(H), rng); idx = rng.permutation(len(S))
    res["names"], _, _ = evaluate([S[i] for i in idx[:len(D)]], [S[i] for i in idx[len(D):]], "names", truth=ntruth)
    # ---- null: Indus bigram process
    mk = Markov(D, 1)
    S = null_corpus(D + H, rng, model=mk); idx = rng.permutation(len(S))
    res["indus_bigram_null"], _, _ = evaluate([S[i] for i in idx[:len(D)]], [S[i] for i in idx[len(D):]], "bigram-null")
    # ---- Indus
    res["indus"], models, voc = evaluate(D, H, "INDUS dev->heldout")
    E, _ = icit_external()
    E = [t for t in E if t not in set(D)]
    te = [voc.enc(t) for t in E]; ntok = sum(len(t) + 1 for t in te)
    tr = [voc.enc(t) for t in D]
    ext = {"n": len(E), "bigram_kn": -KNBigram(tr, len(voc)).loglik(te) / ntok / np.log(2)}
    for name, m in models.items():
        ext[name] = -m.loglik(batches(te)) / ntok / np.log(2)
    res["indus_external_sites"] = ext
    print("external", {k: round(v, 3) for k, v in ext.items()})

    # ---- slot table for the best LR model on Indus + stability across seeds
    lr_names = [k for k in res["indus"] if k.startswith("lr")]
    best = min(lr_names, key=lambda k: res["indus"][k])
    freq = Counter(s for t in D for s in t)
    rows, paths = describe(models[best], voc, D, freq)
    res["indus_best_lr"] = best
    res["indus_slot_table"] = rows
    res["indus_top_paths"] = [(list(p), n) for p, n in paths.most_common(15)]
    print("\nBest LR:", best)
    for r in rows:
        print(r)
    print("top slot paths:", paths.most_common(12))
    # stability: refit best K with 5 new seeds on random 80% of dev; ARI of token slot labels
    K = models[best].K
    lab = []
    for s in range(5):
        sub = [D[i] for i in np.random.default_rng(100 + s).choice(len(D), int(.8 * len(D)), replace=False)]
        m = HMM(K, len(voc), "lr", True, seed=10 + s); m.fit(batches([voc.enc(t) for t in sub]))
        lab.append([z for t in D for z in m.viterbi(voc.enc(t))])
    aris = [adjusted_rand_score(lab[i], lab[j]) for i in range(5) for j in range(i + 1, 5)]
    res["indus_lr_stability_ARI"] = (float(np.mean(aris)), float(np.min(aris)))
    print("stability ARI mean %.3f min %.3f" % res["indus_lr_stability_ARI"])
    save_json("exp2_profile_hmm", res)


if __name__ == "__main__":
    main()
