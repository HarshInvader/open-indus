#!/bin/bash
# Reproduce the v1.0 headline chain of the Indus decipherment project.
#
# usage:  scripts/reproduce.sh            # runs in a scratch copy; the repo is never overwritten
#         WORK=/path/to/dir scripts/reproduce.sh
#
# What it does, in order:
#   1. corpus: rebuilds the corpus from sources/ into a temp dir and checks the deterministic outputs
#      byte for byte against data/. It does NOT replace data/splits_v2.json (see note below).
#   2. hashes: checks every line of docs/prereg/HASHES.txt against the files on disk (report only).
#   3. headline scripts: copies the repo to a scratch dir and re-runs every headline script cited in
#      README, in dependency order, 20 min cap each. Wave-1 scripts are run twice: once on split v1
#      (what their RESULTS.md used) and once on split v2 (current default).
#   4. compare: diffs every regenerated output against the committed one (scripts/compare_outputs.py).
#
# Notes
#   * Split v2 cannot be regenerated byte for byte: corpus/build.py:splits_v2 breaks ties in a
#     family's majority site with max(set(...)), whose order depends on Python's string hashing
#     (PYTHONHASHSEED). The committed data/splits_v2.json is the frozen split every v2 result uses;
#     its sha256 is checked instead.
#   * Many scripts iterate over sets, so their permutation p-values move slightly with the hash seed.
#     The original runs did not fix it. This script fixes PYTHONHASHSEED=0 so that re-runs agree
#     (S6, 2026-11-28: scripts now run with `-s -P` rather than `-I`. `-I` implies `-E`, and under `-E`
#     Python ignores PYTHONHASHSEED, so the export below had no effect and every run got a random seed.
#     `-s -P` keeps the rest of isolated mode: no user site-packages, script directory not put first.)
#     with each other; values can differ from RESULTS.md within that noise (docs/REPRO_REPORT.md).
#   * Skipped here (heavy, network or human raters): decipherability/run_grid.py, cognate_decipher
#     c1-c4, language/b3_sim.py, phonetic_grid sweeps, substitution/run_power.py, iconography i1-i5,
#     language/fetch_vocab.py, decipherability/fetch_wiki.py, and every cycle-4+ experiment not cited
#     as a README headline. Their committed outputs are what the summarisers below read.
set -u
REPO="$(cd "$(dirname "$0")/.." && pwd)"
PY="$REPO/.venv/bin/python"
[ -x "$PY" ] || { echo "No .venv. Run: python3 -m venv .venv && .venv/bin/pip install -r requirements.txt"; exit 1; }
export PYTHONHASHSEED=${PYTHONHASHSEED:-0}
WORK="${WORK:-$(mktemp -d /tmp/indus_repro.XXXXXX)}"
LOG="$WORK/_logs"; mkdir -p "$LOG"
CAP=1200
fail=0

echo "== 1. corpus rebuild (into $WORK/_corpus) =="
mkdir -p "$WORK/_corpus"
"$PY" -s -P -c "
import sys; sys.path.insert(0, '$REPO/corpus'); import build
from pathlib import Path
build.OUT = Path('$WORK/_corpus')
lines, texts = build.m77(); it = build.icit(); build.splits(texts); build.splits_v2(texts)
print(f'M77 {len(lines)} lines, {sum(len(l[\"signs\"]) for l in lines)} tokens; ICIT {len(it)} inscriptions')
"
for f in m77_lines.jsonl m77_texts.jsonl icit_texts.jsonl splits.json; do
  if cmp -s "$WORK/_corpus/$f" "$REPO/data/$f"; then echo "  SAME  data/$f"; else echo "  DIFF  data/$f"; fail=1; fi
done
want_file=7a2bd876a6b4025b105a4568ecd2cbba8089962863a68bad571b8b473f5d78ca
want_held=0174215dbbcd41c2fa05edcd51e8ac62fa1d8111571a04391df2a7f35bfcfe6a
got_file=$(shasum -a 256 "$REPO/data/splits_v2.json" | cut -d' ' -f1)
got_held=$("$PY" -I -c "import json,hashlib;d=json.load(open('$REPO/data/splits_v2.json'));print(hashlib.sha256('\n'.join(d['heldout']).encode()).hexdigest())")
[ "$got_file" = "$want_file" ] && echo "  OK    data/splits_v2.json file sha256 $want_file" || { echo "  DIFF  data/splits_v2.json file sha256 $got_file"; fail=1; }
[ "$got_held" = "$want_held" ] && echo "  OK    splits_v2 held-out list sha256 $want_held" || { echo "  DIFF  splits_v2 held-out list sha256 $got_held"; fail=1; }
echo "  (a fresh splits_v2 is not expected to match; see notes)"

echo "== 2. prereg hashes =="
cd "$REPO"
ok=0; bad=0
while read -r h f _; do
  case "$h" in [0-9a-f]*) ;; *) continue;; esac
  [ ${#h} -eq 64 ] || continue
  if [ ! -f "$f" ]; then echo "  MISSING  $f"; bad=$((bad+1)); continue; fi
  a=$(shasum -a 256 "$f" | cut -d' ' -f1)
  if [ "$a" = "$h" ]; then ok=$((ok+1)); else
    later=$(grep -c "^$a  $f" docs/prereg/HASHES.txt)
    if [ "$later" -gt 0 ]; then echo "  SUPERSEDED $f (a later amendment line matches)"; else echo "  MISMATCH   $f"; fi
    bad=$((bad+1))
  fi
done < docs/prereg/HASHES.txt
echo "  $ok match, $bad do not"

echo "== 3. headline scripts (scratch copy $WORK/v2 and $WORK/v1) =="
copy() {  # copy repo without .venv; clone files on APFS when possible
  mkdir -p "$1"
  for d in README.md corpus data docs experiments results sources; do
    cp -cR "$REPO/$d" "$1/" 2>/dev/null || cp -R "$REPO/$d" "$1/"
  done
}
run() {  # run DIR area/script.py [args]
  local dir=$1; shift; local s=$1; shift
  local tag; tag=$(basename "$dir")__$(echo "$s $*" | tr '/ ' '__')
  local t0; t0=$(date +%s)
  (cd "$dir" && timeout $CAP "$PY" -s -P "experiments/$s" "$@" > "$LOG/$tag.log" 2>&1)
  local rc=$?
  # scripts that import a sibling common.py need the script dir on sys.path (none of these read raw/)
  if [ $rc -ne 0 ] && grep -q "ModuleNotFoundError\|ImportError" "$LOG/$tag.log"; then
    (cd "$dir" && timeout $CAP "$PY" "experiments/$s" "$@" >> "$LOG/$tag.log" 2>&1); rc=$?
  fi
  printf "  %-4s rc=%-3s %4ss  %s %s\n" "$(basename "$dir")" "$rc" "$(( $(date +%s) - t0 ))" "$s" "$*" | tee -a "$LOG/STATUS.txt"
}
copy "$WORK/v2"; copy "$WORK/v1"
# split v1 copy: wave-1/2 scripts call dev_heldout() with the default, which was v1 when they ran
sed -i.bak 's/def dev_heldout(texts=None, version=2)/def dev_heldout(texts=None, version=1)/' "$WORK/v1/corpus/load.py"
touch "$WORK/_mark"; sleep 1

V2="$WORK/v2"; V1="$WORK/v1"
# wave 1-2 (cycle 0-2): structure, novel_methods, context, language, logograms, functional_reading
for d in "$V1" "$V2"; do
  run $d structure/q1_direction.py; run $d structure/q2_inventory.py; run $d structure/q5_grammar.py; run $d structure/q6_icit.py
  run $d novel_methods/exp1_minimal_pairs.py; run $d novel_methods/exp4_families.py
  run $d context/q1_animal.py; run $d context/q2_registers.py; run $d context/q2b_copper.py
  run $d context/q4_gulf.py; run $d context/q5_chronology.py; run $d context/q6_metrology.py
  run $d logograms/l2_substitution.py; run $d logograms/l3_iconic_seals.py
  run $d functional_reading/g2_tests.py; run $d functional_reading/g4_controls.py
  run $d phonetic_grid/indus.py
  run $d internal_phonetics/run_heldout.py
done
run "$V1" language/a2_parpola.py          # crashes on split v2 (empty null pool in P5); v1 is what RESULTS used
run "$V2" language/a1_key_null.py; run "$V2" language/b3_classify.py; run "$V2" language/b3_realcontrols.py
run "$V2" phonetic_grid/controls.py
# red team and revalidation (v2 split)
for s in r1_fish r2_sixfish r3_registers r4_gulf r5_grammar r6_copper r8_direction; do run "$V2" redteam/$s.py; done
run "$V2" revalidation/revalidate.py
# cycle 3 areas
run "$V2" typology/q1_typology.py heldout 200 500 400 3; run "$V2" typology/q2_gulf.py
run "$V2" core_semantics/h3_confirm.py heldout; run "$V2" core_semantics/s2_classes.py heldout
run "$V2" substitution/run_heldout.py
run "$V2" toponyms/confirm.py final
for s in t1_person_graph t2_offices_locus t3_docket; do run "$V2" administration/$s.py heldout; done
run "$V2" administration/t4_lothal_backs.py
run "$V2" iconography/i6_semantics.py
run "$V2" meluhha/name_shape.py
run "$V2" signlist_robustness/harness.py; run "$V2" signlist_robustness/summarise.py
run "$V2" decipherability/indus_run.py; run "$V2" decipherability/analyze.py
run "$V2" cognate_decipher/summarize.py
run "$V2" literature/build_proposals.py
# ledger last: it re-runs v1-only claims on v2 and rebuilds docs/test_ledger.csv (in the scratch copy)
run "$V2" ledger/v2_reruns.py; run "$V2" ledger/build_ledger.py

echo "== 4. compare against committed outputs =="
AREAS="structure novel_methods context language logograms functional_reading phonetic_grid internal_phonetics redteam revalidation typology core_semantics substitution toponyms administration iconography meluhha signlist_robustness decipherability cognate_decipher literature ledger"
echo "-- split v1 copy (should match wave-1 RESULTS.md) --"
"$PY" -I "$REPO/scripts/compare_outputs.py" "$V1" "$WORK/_mark" $AREAS | tee "$LOG/compare_v1.txt" | tail -1
echo "-- split v2 copy --"
"$PY" -I "$REPO/scripts/compare_outputs.py" "$V2" "$WORK/_mark" $AREAS | tee "$LOG/compare_v2.txt" | tail -1
cmp -s "$V2/docs/test_ledger.csv" "$REPO/docs/test_ledger.csv" && echo "  docs/test_ledger.csv SAME" || echo "  docs/test_ledger.csv DIFF (see docs/REPRO_REPORT.md on hash-seed noise)"
echo "Logs and full comparisons: $LOG"
exit $fail
